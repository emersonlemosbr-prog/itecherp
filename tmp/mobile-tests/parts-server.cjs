const path=require('path'),fs=require('fs'),os=require('os');
const root=path.resolve(__dirname,'../..');
const Database=require('../../backend/node_modules/better-sqlite3');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'itech-parts-ui-'));
const source=new Database('C:/ProgramData/iTechERP/backend/db/itech.db',{readonly:true});
const before=source.prepare('SELECT * FROM frontals_price_list ORDER BY id').all();
source.prepare('VACUUM INTO ?').run(path.join(dir,'copy.db'));source.close();
process.env.ITECH_DB_PATH=path.join(dir,'copy.db');process.env.JWT_SECRET='isolated-parts-ui';
const db=require('../../backend/db/database');
const after=db.prepare('SELECT * FROM frontals_price_list ORDER BY id').all();
require('assert/strict').equal(after.length,before.length);
for(let i=0;i<before.length;i++) for(const key of Object.keys(before[i])) require('assert/strict').deepEqual(after[i][key],before[i][key]);
console.log('All '+before.length+' production records preserved field for field in isolated migration.');
const express=require('../../backend/node_modules/express');
const app=express();app.use(express.json());
app.use('/api/calculators',require('../../backend/routes/calculators'));
app.use('/api/auth',require('../../backend/routes/auth'));
app.use('/api/settings',require('../../backend/routes/settings'));
app.get('/api/*',(req,res)=>res.json([]));
app.use(express.static(path.join(root,'frontend/dist')));
app.get('*',(req,res)=>res.sendFile(path.join(root,'frontend/dist/index.html')));
const user=db.prepare('SELECT * FROM users WHERE id=(SELECT user_id FROM frontals_price_list LIMIT 1)').get();
const token=require('../../backend/node_modules/jsonwebtoken').sign({id:user.id,session_version:user.session_version},process.env.JWT_SECRET);
fs.writeFileSync(path.join(__dirname,'parts-ui-auth.json'),JSON.stringify({token,user:{id:user.id,role:user.role,full_name:'Teste isolado'},dir}));
app.listen(3318,'127.0.0.1',()=>console.log('Isolated parts UI ready on 3318; legacy rows: '+db.prepare('SELECT count(*) AS n FROM frontals_price_list').get().n));
